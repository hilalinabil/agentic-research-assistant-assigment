"""Reproducible evaluation runner.

Runs the full agent (same code path as POST /ask) on each question in
eval/questions.json and stores the complete response of every question —
plan, corpus coverage, tool calls, evidence, critic reviews, final answer,
citations — in a new, never-overwritten run directory:

    eval/results/<run_id>/   Q1.json … X1.json, summary.json, RESULTS.md
    eval/results/latest.txt  id of the most recent complete run

summary.json records what is needed to reproduce/compare a run: chat and
embedding model, agent limits, git HEAD, and a SHA-256 fingerprint of the
application code and corpus. LLM output is not deterministic, so two runs of
the same fingerprint can still differ; that is why every run is kept.

Automatic checks are deterministic only:
  * expected source files cited (assignment's expected-source table)
  * all citations valid (app/rag/evidence.py: validate_citations)
  * for control questions: expected status and no citations
No numeric "quality score" is produced; answer correctness is judged by a
human against the cited lines (eval/MANUAL_REVIEW.md).

Usage:
    python -m eval.run_eval                 # all questions (live LLM calls)
    python -m eval.run_eval Q3 Q4           # selected questions (still a new run directory)
    python -m eval.run_eval --report [ID]   # re-render RESULTS.md of a run from its JSON (no LLM calls)
"""
from __future__ import annotations

import hashlib
import json
import logging
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

from app.agent.agent import ResearchAgent
from app.core.config import BASE_DIR, settings
from app.core.llm_client import get_openai_client
from app.retrieval.embedder import Embedder
from app.retrieval.index import build_index

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"


def code_fingerprint() -> str:
    """SHA-256 over application source and corpus files (path + content)."""
    h = hashlib.sha256()
    files = sorted((BASE_DIR / "app").rglob("*.py")) + sorted((BASE_DIR / "app" / "data" / "corpus").glob("*"))
    for f in files:
        h.update(str(f.relative_to(BASE_DIR)).encode())
        h.update(f.read_bytes())
    return h.hexdigest()[:16]


def git_head() -> str:
    try:
        head = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True,
                              cwd=BASE_DIR, check=True).stdout.strip()
        dirty = subprocess.run(["git", "status", "--porcelain"], capture_output=True, text=True,
                               cwd=BASE_DIR).stdout.strip()
        return f"{head}{' (uncommitted changes)' if dirty else ''}"
    except Exception:
        return "unknown"


def checks_for(q: dict, out) -> dict:
    cited = set(out.sources)
    checks = {
        "expected_sources_cited": {s: s in cited for s in q["expected_sources"]},
        "all_expected_sources_cited": all(s in cited for s in q["expected_sources"]),
        "invalid_citations": out.trace["invalid_citations"],
        "num_valid_citations": len(out.citations),
        "removed_citations": out.trace.get("removed_citations", []),
        "revised": out.trace["revised"],
    }
    if "expected_status" in q:
        checks["expected_status_met"] = out.status == q["expected_status"]
        checks["no_citations"] = not out.citations
    return checks


def render_report(run_dir: Path) -> Path:
    summary = json.loads((run_dir / "summary.json").read_text())
    meta = summary["meta"]
    lines = [
        f"# Evaluation run {meta['run_id']}",
        "",
        f"- Chat model `{meta['model']}` · embeddings `{meta['embedding_model']}`",
        f"- Code+corpus fingerprint `{meta['code_fingerprint']}` · git `{meta['git_head']}`",
        f"- Agent limits: {meta['agent_limits']}",
        "",
        "Generated by `python -m eval.run_eval`. Checks are deterministic; answer quality is judged by a human in "
        "`eval/MANUAL_REVIEW.md`. Q1–Q4 are the public assessment questions; X1 is an out-of-corpus control.",
        "",
        "| ID | Status | Expected sources cited | Invalid cit. | Valid cit. | Removed cit. | Tool calls | Revised | Time (s) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in summary["results"]:
        expected = "n/a (control)" if not r["expected_sources_cited"] else (
            "yes" if r["all_expected_sources_cited"] else "NO")
        if "expected_status_met" in r:
            expected += f"; status as expected: {'yes' if r['expected_status_met'] else 'NO'}"
        lines.append(f"| {r['id']} | {r['status']} | {expected} | {len(r['invalid_citations'])} | "
                     f"{r['num_valid_citations']} | {len(r['removed_citations'])} | {r['tool_calls']} | "
                     f"{'yes' if r['revised'] else 'no'} | {r['elapsed_seconds']} |")
    for r in summary["results"]:
        rec = json.loads((run_dir / f"{r['id']}.json").read_text())
        resp, trace = rec["response"], rec["response"]["trace"]
        lines += ["", "---", "", f"## {rec['id']}: {rec['question']}", "",
                  f"Expected sources: {', '.join(rec['expected_sources']) or 'none'} · "
                  f"cited: {', '.join(resp['sources']) or 'none'}", "",
                  f"Corpus coverage: {trace.get('corpus_coverage')}", "", "**Plan**", ""]
        lines += [f"{i}. {s}" for i, s in enumerate(trace["plan"]["sub_questions"], 1)]
        lines += ["", "**Tool calls (chosen by the model)**", ""]
        lines += [f"{i}. `{t['tool']}` `{t['arguments']}` → {t['summary']}" for i, t in enumerate(trace["tool_calls"], 1)]
        lines += ["", "**Critic reviews**", ""]
        for i, rv in enumerate(trace["reviews"], 1):
            lines.append(f"{i}. verdict **{rv['verdict']}**")
            for key in ("unsupported_claims", "citation_problems", "irrelevant_citations", "number_problems",
                        "clinical_ambiguities", "missing_aspects", "source_conflicts", "overrides"):
                for item in rv.get(key) or []:
                    lines.append(f"   - {key.replace('_', ' ')}: {item}")
        if trace.get("removed_citations"):
            lines += ["", f"Removed as irrelevant: {', '.join(trace['removed_citations'])}"]
        lines += ["", "**Final answer**", ""]
        lines += ["> " + ln if ln else ">" for ln in resp["answer"].splitlines()]
    out = run_dir / "RESULTS.md"
    out.write_text("\n".join(lines) + "\n")
    return out


def main(args: list[str]) -> int:
    if args[:1] == ["--report"]:
        run_id = args[1] if len(args) > 1 else (RESULTS / "latest.txt").read_text().strip()
        print(f"Wrote {render_report(RESULTS / run_id)}")
        return 0

    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s: %(message)s")
    for noisy in ("httpx", "httpx2", "openai"):
        logging.getLogger(noisy).setLevel(logging.WARNING)

    questions = json.loads((HERE / "questions.json").read_text())
    if args:
        questions = [q for q in questions if q["id"] in args]

    run_id = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H-%M-%SZ")
    run_dir = RESULTS / run_id
    run_dir.mkdir(parents=True)
    meta = {
        "run_id": run_id,
        "model": settings.openai_model,
        "embedding_model": settings.openai_embedding_model,
        "code_fingerprint": code_fingerprint(),
        "git_head": git_head(),
        "agent_limits": {"max_agent_iterations": settings.max_agent_iterations,
                         "max_tool_calls": settings.max_tool_calls, "max_search_top_k": settings.max_search_top_k,
                         "max_evidence_chars": settings.max_evidence_chars},
        "questions": [q["id"] for q in questions],
    }

    client = get_openai_client()
    index = build_index(settings, Embedder(client, settings.openai_embedding_model, settings.embedding_batch_size))
    agent = ResearchAgent(client, settings, index)

    results = []
    for q in questions:
        print(f"\n=== {q['id']}: {q['question']}")
        out = agent.run(q["question"])
        record = {**q, "status": out.status, "checks": checks_for(q, out), "response": out.model_dump()}
        results.append(record)
        (run_dir / f"{q['id']}.json").write_text(json.dumps(record, indent=2, ensure_ascii=False))
        print(f"status={out.status} sources={out.sources} checks={record['checks']}")

    summary = {
        "meta": meta,
        "results": [{"id": r["id"], "status": r["status"], **r["checks"],
                     "tool_calls": len(r["response"]["trace"]["tool_calls"]),
                     "elapsed_seconds": r["response"]["trace"]["elapsed_seconds"]} for r in results],
    }
    (run_dir / "summary.json").write_text(json.dumps(summary, indent=2))
    print(f"Wrote {render_report(run_dir)}")
    if not args:
        (RESULTS / "latest.txt").write_text(run_id + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
